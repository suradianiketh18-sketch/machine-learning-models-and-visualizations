# Helper function to compute ROUGE scores
def compute_rouge(model, tokenizer, dataset):
    predictions = []
    references = []

    # Ensure model is in evaluation mode and on the correct device
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model.to(device)
    model.eval()

    with torch.no_grad(): # Disable gradient calculations for evaluation
        for example in dataset:
            # Prepare input for generation
            input_ids = example['input_ids'].unsqueeze(0).to(device)
            attention_mask = example['attention_mask'].unsqueeze(0).to(device)

            # Generate prediction
            output_ids = model.generate(
                input_ids=input_ids,
                attention_mask=attention_mask,
                max_length=64,
                num_beams=4, # Use beam search for better generation quality
                early_stopping=True
            )

            predicted_answer = tokenizer.decode(output_ids[0], skip_special_tokens=True)
            predictions.append(predicted_answer)

            # Get reference answer (remove -100 used for loss masking)
            reference_ids = [id_ for id_ in example['labels'].cpu().tolist() if id_ != -100]
            reference_answer = tokenizer.decode(reference_ids, skip_special_tokens=True)
            references.append(reference_answer)

    # Compute ROUGE scores
    results = rouge_metric.compute(predictions=predictions, references=references, use_stemmer=True)
    # The 'results' object now directly contains the scores as floats, not objects with .mid.fmeasure
    return {k: round(v * 100, 4) for k, v in results.items()}

