# Function to create sequences for LSTM training
# X: sequences of 'lookback' timesteps from the input data
# y: sequences of 'predict_timesteps' target values immediately following the lookback window
def create_train_sequences(data_scaled_df, original_paddock_ids_series, lookback, predict_timesteps, target_feature, numerical_features_list):
    X, y = [], []
    unique_paddocks = original_paddock_ids_series.unique()
    target_feature_index = numerical_features_list.index(target_feature)

    for paddock_id in unique_paddocks:
        # Get data for the current paddock
        paddock_data_scaled = data_scaled_df[original_paddock_ids_series == paddock_id].values

        # Loop through the paddock data to create sequences
        # We need enough data for the lookback window and the prediction window
        for i in range(len(paddock_data_scaled) - lookback - predict_timesteps + 1):
            X.append(paddock_data_scaled[i:(i + lookback)])
            y.append(paddock_data_scaled[(i + lookback):(i + lookback + predict_timesteps), target_feature_index])

    return np.array(X), np.array(y)

# Function to create sequences for LSTM evaluation (predicting the reserved test set)
# X_eval: last 'lookback' timesteps from training data for each paddock
# y_eval: 'predict_timesteps' target values from test data for each paddock
def create_eval_sequences(df_scaled_train, df_train_paddock_ids, df_scaled_test, df_test_paddock_ids, lookback, predict_timesteps, target_feature, numerical_features_list):
    X_eval, y_eval = [], []
    unique_paddocks_in_test = df_test_paddock_ids.unique()
    target_feature_index = numerical_features_list.index(target_feature)

    for paddock_id in unique_paddocks_in_test:
        train_paddock_data_scaled = df_scaled_train[df_train_paddock_ids == paddock_id]
        test_paddock_data_scaled = df_scaled_test[df_test_paddock_ids == paddock_id]

        if len(train_paddock_data_scaled) < lookback:
            print(f"Skipping paddock {paddock_id} for evaluation: not enough training data ({len(train_paddock_data_scaled)} timesteps) for lookback window ({lookback}).")
            continue
        if len(test_paddock_data_scaled) != predict_timesteps:
            print(f"Skipping paddock {paddock_id} for evaluation: test data has {len(test_paddock_data_scaled)} timesteps, expected {predict_timesteps}.")
            continue

        # Input sequence for prediction: the last 'lookback' timesteps from the training set
        X_eval.append(train_paddock_data_scaled.iloc[-lookback:].values)

        # Target sequence for evaluation: the actual 'predict_timesteps' from the test set
        y_eval.append(test_paddock_data_scaled.iloc[:, target_feature_index].values)

    return np.array(X_eval), np.array(y_eval)


